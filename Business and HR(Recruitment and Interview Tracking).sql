CREATE DATABASE BUSINESSDB;
USE BUSINESSDB;

# DATABASE DESIGN AND TABLE CREATION:
# CANDIDATES TABLE
CREATE TABLE CANDIDATES(
CANDIDATE_ID INT PRIMARY KEY NOT NULL ,
FULL_NAME INT NOT NULL,
EMAIL VARCHAR(150) UNIQUE NOT NULL,
PHONE_NO VARCHAR(20) UNIQUE NOT NULL,
RESUME_LINK VARCHAR(145) NOT NULL
);

# MODIFY DATATYPE OF FULL_NAME 
ALTER TABLE CANDIDATES
MODIFY FULL_NAME VARCHAR(150) NOT NULL;

DESC CANDIDATES;

# JOBPOSITIONS TABLE
CREATE TABLE JOBPOSITIONS(
POSITION_ID INT PRIMARY KEY NOT NULL,
TITLE VARCHAR(100) NOT NULL,
DEPARTMENT VARCHAR(50) NOT NULL,
OPEN_DATE DATE NOT NULL
);

# RENAMING THE COLUMN 
ALTER TABLE JOBPOSITIONS
RENAME COLUMN TITLE TO JOB_TITLE; 

DESC JOBPOSITIONS;

# APPLICATIONS TABLE
CREATE TABLE APPLICATIONS(
APPLICATION_ID INT PRIMARY KEY NOT NULL,
CANDIDATE_ID INT NOT NULL,
POSITION_ID INT NOT NULL,
APPLIED_DATE DATE NOT NULL,
APPLICATION_STATUS VARCHAR(50) NOT NULL,
FOREIGN KEY (CANDIDATE_ID)
	REFERENCES CANDIDATES (CANDIDATE_ID),
FOREIGN KEY (POSITION_ID)
	REFERENCES JOBPOSITIONS (POSITION_ID)
);

# INTERVIEWROUNDS TABLE
CREATE TABLE INTERVIEWROUNDS(
ROUND_ID INT PRIMARY KEY NOT NULL,
APPLICATION_ID INT NOT NULL,
ROUND_TYPE VARCHAR(50) NOT NULL,
SCHEDULED_DATE DATE NOT NULL,
RESULT VARCHAR(20) NOT NULL,
FOREIGN KEY (APPLICATION_ID)
	REFERENCES APPLICATIONS(APPLICATION_ID)
);

# INTERVIEWERS TABLE
CREATE TABLE INTERVIEWERS(
INTERVIEWER_ID INT PRIMARY KEY NOT NULL,
NAME VARCHAR(100) NOT NULL,
DEPARTMENY VARCHAR(50) NOT NULL,
EMAIL VARCHAR(150) NOT NULL
);

ALTER TABLE INTERVIEWERS
RENAME COLUMN DEPARTMENY TO DEPARTMENT;

# FEEDBACK TABLE
CREATE TABLE FEEDBACK(
FEEDBACK_ID INT PRIMARY KEY NOT NULL,
ROUND_ID INT NOT NULL,
INTERVIEWER_ID INT NOT NULL,
COMMENTS TEXT NOT NULL,
RATING INT NOT NULL,
FOREIGN KEY (ROUND_ID)
	REFERENCES INTERVIEWROUNDS(ROUND_ID),
FOREIGN KEY (INTERVIEWER_ID)
	REFERENCES INTERVIEWERS(INTERVIEWER_ID)
);

