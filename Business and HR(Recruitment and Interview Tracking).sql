CREATE VIEW APPLICATION_SUMMARY AS
SELECT 
C.FULL_NAME,
J.JOB_TITLE,
A.APPLICATION_STATUS,
COUNT(IR.ROUND_ID) AS TOTAL_ROUNDS
FROM APPLICATIONS A
JOIN CANDIDATES C 
ON A.CANDIDATE_ID = C.CANDIDATE_ID
JOIN JOBPOSITIONS J 
ON A.POSITION_ID = J.POSITION_ID
LEFT JOIN INTERVIEWROUNDS IR
ON A.APPLICATION_ID = IR.APPLICATION_ID
GROUP BY C.FULL_NAME, J.JOB_TITLE, A.APPLICATION_STATUS;

CREATE VIEW PUBLIC_APPLICATION_REPORT AS
SELECT 
C.FULL_NAME,
J.JOB_TITLE,
J.DEPARTMENT,
A.APPLICATION_STATUS
FROM APPLICATIONS A
JOIN CANDIDATES C
ON A.CANDIDATE_ID = C.CANDIDATE_ID
JOIN JOBPOSITIONS J
ON A.POSITION_ID = J.POSITION_ID;

